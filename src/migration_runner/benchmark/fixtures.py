"""Generate incompressible fixtures inside OCI, outside the timed benchmark."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import time
from datetime import datetime, timezone
from .contracts import Run, Fixture


def fixture_part(campaign, key, number, size):
    seed = f'oci-benchmark-v1/{campaign}/{key}/{number}'.encode('ascii')
    return hashlib.shake_256(seed).digest(size)


def seed_fixture(client, run, key, size, *, models, part_bytes=32 * 1024**2, parallel_parts=4):
    """SDK client injection makes multipart commit/abort faults testable offline.

    Seed identity needs temporary scoped multipart create/overwrite/abort grants. A source
    object that already exists is rejected. The caller persists each returned
    manifest entry before proceeding. No static cloud credentials are accepted.
    """
    run = Run.model_validate(run)
    run.reference('source', key)
    if type(size) is not int or not 1 <= size <= 10_000_000_000:
        raise ValueError('Fixture size must be 1 byte through 10 GB')
    if not 1024**2 <= part_bytes <= 128 * 1024**2:
        raise ValueError('Fixture generation buffer is outside bounds')
    if type(parallel_parts) is not int or not 1 <= parallel_parts <= 4:
        raise ValueError('Fixture uploads permit at most four parallel parts')
    deadline = time.monotonic() + run.max_seconds

    def check():
        if time.monotonic() >= deadline or datetime.now(timezone.utc) >= run.expiry():
            raise ValueError('Fixture generation deadline reached')

    check()
    try:
        client.head_object(run.namespace, run.source_bucket, key)
    except Exception as exc:
        if getattr(exc, 'status', None) != 404:
            raise
    else:
        raise ValueError('Source fixture already exists; use a new key')
    upload = client.create_multipart_upload(run.namespace, run.source_bucket,
        models.CreateMultipartUploadDetails(object=key, content_type='application/octet-stream')).data
    committed = False
    digest = hashlib.sha256()
    parts = []
    try:
        remaining, number = size, 1
        pending = []
        def finish(part_number, future):
            response = future.result()
            parts.append(models.CommitMultipartUploadPartDetails(part_num=part_number, etag=response.headers['etag']))
        # At most four part payloads in flight, plus the current generation buffer.
        # Wait for all submitted parts before aborting after a failure/interruption.
        with ThreadPoolExecutor(max_workers=parallel_parts) as pool:
            while remaining:
                check()
                data = fixture_part(run.campaign, key, number, min(part_bytes, remaining))
                digest.update(data)
                pending.append((number, pool.submit(client.upload_part, run.namespace, run.source_bucket,
                                                    key, upload.upload_id, number, data)))
                remaining -= len(data)
                number += 1
                if len(pending) >= parallel_parts:
                    finish(*pending.pop(0))
            for item in pending:
                finish(*item)
        check()
        client.commit_multipart_upload(run.namespace, run.source_bucket, key, upload.upload_id,
            models.CommitMultipartUploadDetails(parts_to_commit=parts))
        committed = True
        metadata = client.head_object(run.namespace, run.source_bucket, key).headers
        from email.utils import parsedate_to_datetime
        if int(metadata['content-length']) != size:
            raise ValueError('Committed fixture size differs from generated bytes')
        return Fixture(key=key, size=size, sha256=digest.hexdigest(),
                       last_modified=parsedate_to_datetime(metadata['last-modified']).isoformat())
    finally:
        if not committed:
            client.abort_multipart_upload(run.namespace, run.source_bucket, key, upload.upload_id)
